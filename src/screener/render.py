"""Code builds the evidence table and summary text from validated output (ADR 0005).

Synthetic and PubMed records always appear in separate, labelled sections.
Output is plain text, because the email is sent as plain text (ADR 0013).
"""
from __future__ import annotations

from screener.drafting import NO_SYNTHESIS
from screener.models import (
    EvidenceItem,
    PubmedSearch,
    Record,
    ReviewWarning,
    ScreeningDecision,
    SourceType,
    SummaryDraft,
)

SECTION_TITLES = {
    "synthetic": "SYNTHETIC DATASET (fictional test records, not medical evidence)",
    "pubmed": "PUBMED (live search)",
}


def cite(record: Record) -> str:
    return f"[PMID {record.pmid}]" if record.source_type == "pubmed" else f"[{record.record_id}]"


def pubmed_header(search: PubmedSearch, recency: bool, recency_years: int) -> list[str]:
    # The full query string is kept in the run file and trace only (ADR 0012).
    lines = [
        f"Search date: {search.max_date}",
        f"Date window: {search.min_date} to {search.max_date}"
        + (f" (recent = published in the {recency_years} years before the search date)" if recency else ""),
        f"Screened {len(search.retrieved_pmids)} of {search.total_matches} total matches (top results by relevance).",
    ]
    if search.status == "no_results":
        lines.append("No PubMed records matched the query in this date window.")
    if search.status == "unavailable":
        lines.append("PubMed was unavailable after retries; no live results are included.")
    return lines


def render_summary(summary: SummaryDraft, records: dict[str, Record], decisions: list[ScreeningDecision],
                   sources: list[SourceType]) -> str:
    out: list[str] = []
    for source in sources:
        out += ["", SECTION_TITLES[source]]
        included = [d.record_id for d in decisions if d.decision == "include" and d.source_type == source]
        claims = [c for c in summary.claims if records[c.record_ids[0]].source_type == source]
        claims.sort(key=lambda c: c.kind == "comparison")  # the comparison is shown last in its section
        if not included:
            out.append("No studies in this source met the screening rules; see the evidence table for reasons.")
        elif not claims:
            out.append(NO_SYNTHESIS)
        else:
            out += [f"- {c.text} {' '.join(cite(records[r]) for r in c.record_ids)}" for c in claims]
    return "\n".join(out).strip()


DISCLAIMER = (
    "Synthetic records are fictional test fixtures, not medical evidence. "
    "This prototype does not provide medical advice."
)


def default_subject(question: str, search_date: str, run_id: str) -> str:
    short = question if len(question) <= 80 else question[:77].rstrip() + "..."
    return f"Literature screen: {short} ({search_date}) [run {run_id}]"


def footer(run_id: str) -> str:
    """Generated by code and never editable, so the run ID survives subject edits (ADR 0013)."""
    return f"--\nRun ID: {run_id}\n{DISCLAIMER}"


_SOURCE_NAMES = {"synthetic": "synthetic dataset", "pubmed": "PubMed"}


def email_limitations(warnings: list[ReviewWarning]) -> list[str]:
    """Fixed sentences for the email, chosen by code from the run state (ADR 0007).

    Only three cases are reported to the recipient: a source unavailable, no
    synthesis produced, and no cross-study comparison. All other warnings, such as
    removed claims and Critic issues, are reviewer notes and are never sent.
    """
    lines: list[str] = []
    for w in warnings:
        if w.kind == "source_unavailable":
            lines.append(f"{_SOURCE_NAMES[w.source or 'pubmed']} could not be searched (unavailable after retries), "
                         "so its results are not included.")
        elif w.kind == "no_synthesis":
            lines.append("No plain-language summary could be produced for the included studies; "
                         "the evidence table lists them.")
        elif w.kind == "missing_comparison":
            lines.append(f"The summary does not compare the direction of findings across the included "
                         f"{_SOURCE_NAMES[w.source or 'pubmed']} studies.")
    return list(dict.fromkeys(lines))


def render_email_body(*, question: str, interpretation: str, summary_text: str, limitations: list[str],
                      evidence_text: str, run_id: str) -> str:
    parts = ["QUESTION", question, "", "INTERPRETATION", interpretation, "", "SUMMARY", summary_text]
    if limitations:
        parts += ["", "LIMITATIONS", *[f"- {line}" for line in limitations]]
    parts += ["", evidence_text, "", footer(run_id)]
    return "\n".join(parts)


def _short(text: str, limit: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 3].rstrip() + "..."


def _rule_support(rule: str, evidence: list[EvidenceItem]) -> EvidenceItem | None:
    """The evidence item behind a failed rule, so each exclusion line cites its supporting text."""
    if rule.startswith("out of scope: "):
        prefixes: tuple[str, ...] = (f"{rule.removeprefix('out of scope: ').split()[0]} does not match",)
    elif rule == "animal study":
        prefixes = ("species",)
    elif rule.startswith(("non-randomised", "not a randomised")):
        prefixes = ("design",)
    elif rule.startswith("published before"):
        prefixes = ("published",)
    elif rule.endswith("or fewer participants"):
        prefixes = ("total sample size", "group size")
    elif rule.startswith("trial protocol"):
        prefixes = ("publication type",)
    else:
        return None
    return next((e for e in evidence if e.fact.startswith(prefixes)), None)


def _support(e: EvidenceItem | None) -> str:
    if e is None:
        return ""
    return f' | "{_short(e.quote, 110)}"' if e.quote else f" | {e.fact} (metadata)"


def _one_line(d: ScreeningDecision, r: Record) -> str:
    head = f"- {cite(r)} {r.title} ({r.publication_year or 'year unknown'})"  # full title: the brief asks for actual titles
    if d.decision == "needs_review":
        line = f"{head}: missing or unclear: {'; '.join(d.missing_details)}"
    else:
        suffix = " (other rules not checked)" if d.metadata_only else ""
        line = f"{head}: {'; '.join(d.failed_rules)}{suffix}{_support(_rule_support(d.failed_rules[0], d.evidence))}"
    return f"{line} {r.url}" if r.url else line


def render_evidence_table(summary: SummaryDraft, records: dict[str, Record], decisions: list[ScreeningDecision],
                          sources: list[SourceType], pubmed_lines: list[str] | None = None) -> str:
    """Compact table for the review screen and email (ADR 0007). Full per-record evidence stays in the run file.

    Included studies show their key evidence fields with quotes; needs-review and
    excluded records get one line each, with the missing detail or the failed rule
    and its supporting quote or metadata.
    """
    details = {sd.record_id: sd.details for sd in summary.study_details}
    out: list[str] = []
    for source in sources:
        out += ["", f"EVIDENCE TABLE: {SECTION_TITLES[source]}"]
        if source == "pubmed" and pubmed_lines:
            out += pubmed_lines
        section = [d for d in decisions if d.source_type == source]
        if not section:
            out.append("No records retrieved.")
            continue
        groups = {k: [d for d in section if d.decision == k] for k in ("include", "needs_review", "exclude")}
        out += ["", f"Included ({len(groups['include'])})"]
        for d in groups["include"]:
            r = records[d.record_id]
            out.append(f"{cite(r)} {r.title} ({r.publication_year or 'year unknown'})")
            if r.url:
                out.append(f"  {r.url}")
            for sd in details.get(d.record_id, []):
                quote = f' ["{_short(sd.quote, 140)}"]' if sd.quote else ""
                out.append(f"  {sd.name.replace('_', ' ')}: {sd.value}{quote}")
        out += ["", f"Needs review ({len(groups['needs_review'])})"]
        out += [_one_line(d, records[d.record_id]) for d in groups["needs_review"]]
        out += ["", f"Excluded ({len(groups['exclude'])})"]
        out += [_one_line(d, records[d.record_id]) for d in groups["exclude"]]
    return "\n".join(out).strip()
